kommersant = "🌐 Минцифры не планирует вводить ограничения на доступ детей в соцсети, заявил глава Минцифры Максут Шадаев. Ранее на портале проектов нормативных правовых актов были опубликованы поправки «Правил оказания услуг телефонной связи», предполагающие дополнительную защиту для детских сим-карт. 📡 Тренды телекома. Коротко и по делу. Подписывайтесь ."

varlamov = "Минцифры предложило запретить смс-рассылки на детские сим-карты, в том числе смс для авторизации на интернет-ресурсах. Это может лишить детей доступа к мессенджерам и соцсетям, заявили в «Вымпелкоме». Такое предложение Минцифры представило в проекте постановления на портале правовых актов. «Вымпелком» в своем отзыве на документ предполагает, что запрет смс-рассылки может коснуться в том числе идентификационных смс от «ВКонтакте» и мессенджера «Макс»: «Мессенджеры являются основным и наиболее оперативным каналом связи между родителями и детьми. Полный запрет доступа детей до 18 лет к этим инструментам лишает абонентов возможности мгновенного обмена важной информацией». В Минцифры сообщили Forbes, что предлагаемая мера призвана снизить риски мошенничества в отношении несовершеннолетних и кражи персональных данных, при этом ведомство предусмотрело исключение для авторизационных смс от госинформсистем, например, от «Госуслуг». Детские сим-карты, о которых идет речь, оформляются совершеннолетними абонентами, которые по своему желанию уведомляют оператора, что сим-карта передана в пользование ребенку."


from transformers import T5ForConditionalGeneration, T5Tokenizer
import torch

print("Загрузка модели суммаризации...")
# Загружаем токенизатор и модель один раз
# Автоматически используем видеокарту, если она есть (или Mac M1/M2/M3)
device = "cuda" if torch.cuda.is_available() else "mps" if torch.backends.mps.is_available() else "cpu"
print(f"Саммаризатор работает на устройстве: {device}")

sum_tokenizer = T5Tokenizer.from_pretrained("IlyaGusev/rut5_base_sum_gazeta")
sum_model = T5ForConditionalGeneration.from_pretrained("IlyaGusev/rut5_base_sum_gazeta").to(device)

def get_summary(text, max_length=90):
    # 1. Динамический паддинг: добивает только до длины самой длинной новости в батче 
    # (в нашем случае - просто обрезает длинные до 500, а короткие не трогает)
    inputs = sum_tokenizer(
        [text],
        max_length=500,
        padding=True, # Изменено здесь
        truncation=True,
        return_tensors="pt"
    ).to(device) # Перекидываем данные на то же устройство, где модель

    # 2. Обязательно передаем attention_mask!
    output_ids = sum_model.generate(
        input_ids=inputs["input_ids"],
        attention_mask=inputs["attention_mask"], # ЭТО СПАСЕТ ОТ ГАЛЛЮЦИНАЦИЙ
        max_length=max_length, # 90 токенов - это примерно 2-3 предложения, больше для выжимки не нужно
        no_repeat_ngram_size=3,
        num_beams=2, # Снизили для скорости
        early_stopping=True
    )[0]

    summary = sum_tokenizer.decode(output_ids, skip_special_tokens=True)
    print(f"Summary: {summary}\n")
    return summary
    

# model = CrossEncoder("s-nlp/ruRoberta-large-paraphrase-v1")
model = CrossEncoder("cointegrated/rubert-base-cased-nli-threeway")

ria_summary = get_summary(ria)
kommersant_summary = get_summary(kommersant)
varlamov_summary = get_summary(varlamov)

pairs = [
    ("ria vs kommersant (ожидаем: НИЗКАЯ вероятность, это контрадикшен)", ria_summary, kommersant_summary),
    ("ria vs varlamov (ожидаем: ВЫСОКАЯ вероятность, это контрадикшен)", ria_summary, varlamov_summary),
]

for label, text_a, text_b in pairs:
    logits = model.predict([(text_a, text_b)], convert_to_tensor=True)
    probs = torch.softmax(logits, dim=-1)
    paraphrase_prob = float(probs[0][1])
    print(f"{label}")
    print(f"  вероятность парафраза: {paraphrase_prob:.3f}\n")